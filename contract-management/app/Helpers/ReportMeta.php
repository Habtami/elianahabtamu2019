<?php

namespace App\Helpers;

use Carbon\Carbon;

class ReportMeta
{
    /**
     * Letterhead data for a printed or exported report.
     *
     * @param  iterable  $rows  records included in the document
     * @param  array<int, string|null>  $filters  human-readable filter labels
     * @return array<string, mixed>
     */
    public static function build($rows, array $filters = [], $from = null, $to = null, string $dateKey = 'created_at', ?int $total = null): array
    {
        $user = auth()->user();
        $rows = collect($rows);

        $from = $from ? Carbon::parse($from) : null;
        $to = $to ? Carbon::parse($to) : null;

        if (! $from && ! $to) {
            $dates = $rows->map(function ($row) use ($dateKey) {
                $value = is_array($row) ? ($row[$dateKey] ?? null) : ($row->{$dateKey} ?? null);

                return $value ? Carbon::parse($value) : null;
            })->filter();

            if ($dates->isNotEmpty()) {
                $from = $dates->min();
                $to = $dates->max();
            }
        }

        $records = $rows->count();

        return [
            'name' => $user->name ?? 'System',
            'role' => method_exists($user, 'getRoleDisplayName') ? $user->getRoleDisplayName() : (string) $user->role,
            'generated_at' => now(),
            'range_label' => ($from && $to)
                ? $from->format('M d, Y').' to '.$to->format('M d, Y')
                : 'No records',
            'records' => $records,
            'total' => $total ?? $records,
            'filters' => collect($filters)->filter()->values(),
        ];
    }

    /**
     * Letterhead lines written above the header row of a spreadsheet export.
     *
     * @param  array<string, mixed>|null  $meta
     * @return array<int, string>
     */
    public static function sheetLines(?array $meta, string $title): array
    {
        if (! $meta) {
            return [];
        }

        return [
            'EPSS - Contract Management System',
            $title,
            'Generated by: '.$meta['name'].' ('.$meta['role'].')',
            'Generated on: '.$meta['generated_at']->format('M d, Y H:i'),
            'Date range: '.$meta['range_label'],
            'Records: '.$meta['records'].($meta['total'] > $meta['records'] ? ' of '.$meta['total'] : ''),
            'Filters: '.($meta['filters']->isEmpty() ? 'None' : $meta['filters']->implode(' | ')),
        ];
    }
}
